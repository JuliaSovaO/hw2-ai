def write_submission(preds, test_df, path, max_dets=500):
    """preds: dict test image_id (e.g. 'clip_001_0000001') -> N x 6 array in original pixels."""
    rows = []
    for iid in test_df.image_id:
        d = preds.get(iid)
        s = ""
        if d is not None and len(d):
            d = d[np.argsort(-d[:, 4])][:max_dets]
            s = " ".join(f"{int(c)} {sc:.4f} {x1:.1f} {y1:.1f} {x2 - x1:.1f} {y2 - y1:.1f}"
                         for x1, y1, x2, y2, sc, c in d)
        rows.append((iid, s))
    sub = pd.DataFrame(rows, columns=["image_id", "PredictionString"])
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    sub.to_csv(path, index=False)
    return sub

def draw_boxes(ax, boxes, classes=None, color=None, scores=None, lw=0.8, ls="-"):
    """boxes: N x 4 [x1, y1, x2, y2]; colour by class unless `color` is given."""
    import matplotlib.patches as mpatches
    import matplotlib.pyplot as plt
    pal = plt.get_cmap("tab10").colors
    for i, b in enumerate(np.asarray(boxes).reshape(-1, 4)):
        c = color or pal[int(classes[i]) % 10]
        ax.add_patch(mpatches.Rectangle((b[0], b[1]), b[2] - b[0], b[3] - b[1], fill=False, ec=c, lw=lw, ls=ls))
        if scores is not None:
            ax.text(b[0], b[1] - 1, f"{scores[i]:.2f}", color=c, fontsize=5)