def load_split(split):
    """Read <split>/annotations_coco.json into three tables.

    imgs: one row per frame (image_id, file_name, width, height, video, frame_id)
    objs: target objects (iscrowd=0) with pixel box x, y, w, h (top-left corner) and 0-based class `cls`
    igns: ignored regions (iscrowd=1): VisDrone "ignored regions" and "others"
    """
    coco = json.load(open(ROOT / split / "annotations_coco.json"))
    imgs = pd.DataFrame(coco["images"]).rename(columns={"id": "image_id"})
    ann = pd.DataFrame(coco["annotations"])
    ann[["x", "y", "w", "h"]] = pd.DataFrame(ann.pop("bbox").tolist(), index=ann.index)
    ann = ann.merge(imgs[["image_id", "video", "frame_id", "width", "height"]], on="image_id")
    objs = ann[ann.iscrowd == 0].copy()
    objs["cls"] = objs.category_id - 1
    objs["cls_name"] = objs.cls.map(dict(enumerate(CLASSES)))
    objs["sqrt_area"] = np.sqrt(objs.w * objs.h)
    imgs["split"] = split
    return imgs, objs, ann[ann.iscrowd == 1].copy()


def frame_key(video, frame_id):
    """File stem used in the processed dataset, e.g. uav0000013_00000_v__0000135."""
    return f"{video}__{int(frame_id):07d}"


def select_frames(imgs, step=None, per_clip=None, offset=0):
    """Sequence-aware frame selection.

    step:     keep every `step`-th frame of each clip (starting at `offset`)
    per_clip: keep at most `per_clip` evenly spaced frames of each clip
    """
    out = []
    for _, g in imgs.sort_values(["video", "frame_id"]).groupby("video"):
        if step:
            g = g.iloc[offset::step]
        if per_clip and len(g) > per_clip:
            g = g.iloc[np.linspace(0, len(g) - 1, per_clip).round().astype(int)]
        out.append(g)
    return pd.concat(out, ignore_index=True)


