def ignore_mask(h, w, igns):
    """Boolean H x W mask that is True inside ignored regions."""
    m = np.zeros((h, w), bool)
    for g in igns.itertuples():
        x0, y0 = max(int(g.x), 0), max(int(g.y), 0)
        x1, y1 = min(int(np.ceil(g.x + g.w)), w), min(int(np.ceil(g.y + g.h)), h)
        m[y0:y1, x0:x1] = True
    return m


def _process_frame(row, split, objs, igns, out_img, out_lbl, mask_ignore, max_side, drop_covered):
    """Read one frame, optionally paint ignored regions grey, resize, write image + YOLO label file."""
    img = cv2.imread(str(ROOT / split / row.file_name))
    H, W = img.shape[:2]
    m = ignore_mask(H, W, igns)
    if mask_ignore:
        img[m] = PAD_VALUE

    # clip boxes to the image, drop degenerate ones
    x0, y0 = objs.x.clip(0, W).values, objs.y.clip(0, H).values
    x1, y1 = (objs.x + objs.w).clip(0, W).values, (objs.y + objs.h).clip(0, H).values
    keep = (x1 - x0 >= 1) & (y1 - y0 >= 1)
    # drop objects that are mostly inside an ignored region (they are painted over)
    covered = np.array([m[int(b):int(np.ceil(d)), int(a):int(np.ceil(c))].mean() if k else 1.0
                        for a, b, c, d, k in zip(x0, y0, x1, y1, keep)])
    if mask_ignore:
        keep &= covered < drop_covered
    cls = objs.cls.values[keep]
    x0, y0, x1, y1 = x0[keep], y0[keep], x1[keep], y1[keep]

    scale = min(1.0, max_side / max(H, W))
    if scale < 1.0:
        img = cv2.resize(img, (round(W * scale), round(H * scale)), interpolation=cv2.INTER_AREA)
    stem = frame_key(row.video, row.frame_id)
    cv2.imwrite(str(out_img / f"{stem}.jpg"), img, [cv2.IMWRITE_JPEG_QUALITY, 95])
    # YOLO format: class cx cy w h, normalised by the image size (resizing does not change them)
    lines = [f"{c} {(a + c2) / 2 / W:.6f} {(b + d) / 2 / H:.6f} {(c2 - a) / W:.6f} {(d - b) / H:.6f}"
             for c, a, b, c2, d in zip(cls, x0, y0, x1, y1)]
    (out_lbl / f"{stem}.txt").write_text("\n".join(lines))
    return {"key": stem, "kept": int(keep.sum()), "dropped": int(len(objs) - keep.sum()),
            "ignored_frac": float(m.mean())}


def build_yolo_dataset(name, splits, max_side=1920, drop_covered=0.5, workers=8):
    """Write data/proc/<name>/{images,labels}/<part>/ and data.yaml.

    splits: dict part -> (source split, frames table, objs table, igns table, mask_ignore flag)
    Returns a table with per-frame statistics.
    """
    out = PROC / name
    stats = []
    for part, (split, frames, objs, igns, mask_ignore) in splits.items():
        out_img, out_lbl = out / "images" / part, out / "labels" / part
        out_img.mkdir(parents=True, exist_ok=True)
        out_lbl.mkdir(parents=True, exist_ok=True)
        obj_g, ign_g = dict(list(objs.groupby("image_id"))), dict(list(igns.groupby("image_id")))
        empty_o, empty_i = objs.iloc[:0], igns.iloc[:0]
        with ThreadPoolExecutor(workers) as ex:
            res = list(ex.map(lambda r: _process_frame(r, split, obj_g.get(r.image_id, empty_o),
                                                        ign_g.get(r.image_id, empty_i), out_img, out_lbl,
                                                        mask_ignore, max_side, drop_covered),
                              frames.itertuples()))
        stats.append(pd.DataFrame(res).assign(part=part))
        frames.to_csv(out / f"{part}_frames.csv", index=False)
    (out / "data.yaml").write_text(
        f"path: {out.resolve()}\ntrain: images/train\nval: images/val\n"
        f"nc: {len(CLASSES)}\nnames: {json.dumps(CLASSES)}\n")
    return pd.concat(stats, ignore_index=True)


