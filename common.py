# Detections everywhere in this project: numpy array N x 6 = [x1, y1, x2, y2, score, cls] in ORIGINAL image
# pixels, cls is 0-based. Predictions for a set of images: dict image_id -> array.


def coco_evaluate(gt_path, preds, max_dets=500, img_ids=None):
    """COCO metrics with up to `max_dets` detections per image (as on Kaggle).

    Returns mAP (= AP@[.5:.95]), AP50, AP75, AP_small/medium/large and per-class AP.
    img_ids: evaluate only these images (e.g. one clip); default all images of the GT file.
    The metrics are read from the precision array directly, because COCOeval.summarize() hard-codes
    100 detections per image for the main AP.
    """
    from pycocotools.coco import COCO
    from pycocotools.cocoeval import COCOeval

    with contextlib.redirect_stdout(io.StringIO()):
        gt = COCO(str(gt_path))
        keep = set(gt.getImgIds() if img_ids is None else img_ids)
        rows = [[iid, d[0], d[1], d[2] - d[0], d[3] - d[1], d[4], int(d[5]) + 1]
                for iid, dets in preds.items() if iid in keep for d in dets[np.argsort(-dets[:, 4])][:max_dets]]
        if not rows:
            return {"mAP": 0.0}
        dt = gt.loadRes(np.array(rows, dtype=np.float64))
        E = COCOeval(gt, dt, "bbox")
        E.params.imgIds = sorted(keep)
        E.params.maxDets = [1, 100, max_dets]
        E.evaluate(); E.accumulate()
    P = E.eval["precision"]  # [IoU thr, recall, class, area, maxDets]

    def ap(t=None, a=0, k=None):
        p = P[:, :, :, a, -1] if t is None else P[[t], :, :, a, -1]
        if k is not None:
            p = p[:, :, k]
        p = p[p > -1]
        return float(p.mean()) if p.size else float("nan")

    res = {"mAP": ap(), "AP50": ap(0), "AP75": ap(5),
           "AP_small": ap(a=1), "AP_medium": ap(a=2), "AP_large": ap(a=3)}
    res.update({f"AP_{c}": ap(k=i) for i, c in enumerate(CLASSES)})
    return res


def gt_as_predictions(gt_path):
    """Ground truth boxes written as perfect detections: a sanity check for the evaluator (must give mAP = 1)."""
    gt = json.load(open(gt_path))
    preds = {im["id"]: [] for im in gt["images"]}
    for a in gt["annotations"]:
        if not a["iscrowd"]:
            x, y, w, h = a["bbox"]
            preds[a["image_id"]].append([x, y, x + w, y + h, 1.0, a["category_id"] - 1])
    return {k: np.array(v, dtype=np.float64).reshape(-1, 6) for k, v in preds.items()}


def time_per_image(fn, items, warmup=3):
    """Average wall time of fn(item) in ms, after a few warm-up calls (GPU kernels, cudnn autotune)."""
    for it in items[:warmup]:
        fn(it)
    try:
        import torch
        sync = torch.cuda.synchronize if torch.cuda.is_available() else (lambda: None)
    except ImportError:
        sync = lambda: None
    sync(); t = time.perf_counter()
    for it in items:
        fn(it)
    sync()
    return (time.perf_counter() - t) / len(items) * 1000


